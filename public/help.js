export function searchHelp(query) {
  const q = String(query || "")
    .trim()
    .toLocaleLowerCase();
  const matches = (values) => values.join(" ").toLocaleLowerCase().includes(q);
  return {
    topics: helpTopics.filter((v) =>
      matches([v.title, v.category, v.summary, ...v.steps]),
    ),
    faqs: helpFaqs.filter(matches),
    terms: helpTerms.filter(matches),
  };
}
